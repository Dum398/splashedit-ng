#!/usr/bin/env python3
"""Regenerates core/licence_psxsplash.inc, the "psxsplash" disc licence
(LBA 0-11 in mkpsxiso's 2336-byte sector format) that core/disc.cpp embeds.

The source is Data/SPLASHLICENSE.DAT from the Unity splashedit package
(MIT, psxsplash), the file Unity builds licensed every disc with.

    python3 tools/gen_licence.py ../splashedit/Data/SPLASHLICENSE.DAT
"""

import hashlib
import os
import sys

src = sys.argv[1]
data = open(src, 'rb').read()
if len(data) != 12 * 2336:
    sys.exit('%s: %d bytes, expected 28032 (12 x 2336)' % (src, len(data)))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'core', 'licence_psxsplash.inc')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_licence.py from splashedit Data/SPLASHLICENSE.DAT\n')
    f.write('// (MIT, psxsplash). %d bytes, sha256 %s\n' % (len(data), hashlib.sha256(data).hexdigest()))
    for i in range(0, len(data), 24):
        f.write(''.join('0x%02x,' % b for b in data[i:i + 24]) + '\n')
print('%s: %d bytes' % (out, len(data)))
